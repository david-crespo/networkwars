// Search Q to win probability. Root Q is the mean of rollouts played by a weak
// policy, so it runs pessimistic: a position the AI's search rates 10% is won
// about 55% of the time when the AI plays it out. Each table gives that win rate
// at Q = i/100, interpolated linearly. Longer searches read close positions
// higher, so each search budget has its own table. Fit by solver/calibrate.py.
const table = (win: number[]) => (q: number) => {
  const x = Math.min(1, Math.max(0, q)) * 100, i = Math.min(99, Math.floor(x));
  return win[i] + (win[i + 1] - win[i]) * (x - i);
};

